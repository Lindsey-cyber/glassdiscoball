"""Make compass.html self-contained.

compass.html normally loads its simulator, model/mouse JSON, the Ripser worker and ripser.wasm from compass/web/.
Browsers refuse all of that when the page is opened as a file, and previewers often show the HTML alone, so this
script bakes everything into one <script> block at the end of compass.html (between the EMBED markers).
The page uses the embedded copy when it is there and falls back to compass/web/ otherwise.

Run after changing anything in compass/web/:   python3 compass/embed.py
"""
import base64, json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
WEB = ROOT / "compass" / "web"
PAGE = ROOT / "compass.html"
BEGIN, END = "<!-- EMBED:BEGIN (generated by compass/embed.py, do not edit) -->", "<!-- EMBED:END -->"


def plain(js):
    """ES module -> plain script: drop import lines and `export` keywords."""
    js = re.sub(r"^import .*?;\n", "", js, flags=re.M)
    js = re.sub(r"^export (?=(async )?(function|const|class|let))", "", js, flags=re.M)
    return js.replace('new URL("./ripser.wasm", import.meta.url).href', '""')


sim = plain((WEB / "sim.js").read_text())
topo = plain((WEB / "ripser-wasm.js").read_text()) + "\n" + plain((WEB / "topo-worker.js").read_text())
wasm = base64.b64encode((WEB / "ripser.wasm").read_bytes()).decode()
data = {f"compass/web/{p.name}": json.loads(p.read_text()) for p in sorted(WEB.glob("*.json"))}

js = "\n".join([
    f'globalThis.__RIPSER_WASM_B64 = "{wasm}";',
    "window.__COMPASS = {",
    f"  sim: (function () {{\n{sim}\nreturn {{ Circuit, CONDITIONS }};\n}})(),",
    "  topoSrc: " + json.dumps(topo) + ",",
    "  get topo() { return this._topo ||= new Function(this.topoSrc + '\\nreturn { handle };')(); },",
    "  get workerSrc() { return `globalThis.__RIPSER_WASM_B64 = ${JSON.stringify(globalThis.__RIPSER_WASM_B64)};\\n${this.topoSrc}`; },",
    "  data: " + json.dumps(data, separators=(",", ":")) + ",",
    "};",
])
block = f"{BEGIN}\n<script>\n{js.replace('</script', '<\\/script')}\n</script>\n{END}\n"

html = PAGE.read_text()
if BEGIN in html:
    html = html[: html.index(BEGIN)] + block + html[html.index(END) + len(END) + 1 :]
else:
    html = html.replace("</body>", block + "</body>")
PAGE.write_text(html)
print(f"compass.html: {len(html) / 1e6:.2f} MB ({len(data)} data files, wasm {len(wasm) / 1e3:.0f} KB base64)")
